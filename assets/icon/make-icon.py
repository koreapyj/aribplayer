"""Generates the ARIB Player app icon: aribplayer.svg (design source) and aribplayer.ico (16-256 px).

A TV with a play triangle and a caption bar; no letters or text. Standard library only:
    python assets/icon/make-icon.py [--preview-dir DIR]
writes aribplayer.svg and aribplayer.ico next to this script and, with --preview-dir, preview-<size>.png files.

Geometry is in a 256-unit box. Sizes up to 24 px use a chunkier variant without the stand so it stays readable.
ICO entries: 32-bit BGRA bitmaps with an AND mask for 16-64 px, PNG for 256 px.
"""
import argparse
import os
import struct
import zlib

SIZES = [16, 20, 24, 32, 40, 48, 64, 256]

BLUE = (0x2B, 0x6C, 0xDF)
SCREEN = (0x0E, 0x15, 0x25)
WHITE = (0xFF, 0xFF, 0xFF)
YELLOW = (0xFF, 0xC8, 0x3D)

# (kind, color, geometry): rrect = (x0, y0, x1, y1, radius), tri = ((x, y), (x, y), (x, y)). Painted in order.
FULL = [
    ("rrect", BLUE, (12, 36, 244, 204, 32)),          # TV body
    ("rrect", BLUE, (92, 212, 164, 228, 8)),           # stand
    ("rrect", SCREEN, (30, 54, 226, 186, 18)),         # screen
    ("tri", WHITE, ((106, 72), (106, 140), (164, 106))),   # play
    ("rrect", YELLOW, (70, 154, 186, 170, 8)),         # caption bar
]
SMALL = [
    ("rrect", BLUE, (0, 24, 256, 232, 40)),
    ("rrect", SCREEN, (24, 48, 232, 208, 16)),
    ("tri", WHITE, ((96, 64), (96, 148), (176, 106))),
    ("rrect", YELLOW, (56, 166, 200, 190, 12)),
]


def inside(kind, g, x, y):
    if kind == "rrect":
        x0, y0, x1, y1, r = g
        if x < x0 or x > x1 or y < y0 or y > y1:
            return False
        dx = max(x0 + r - x, 0, x - (x1 - r))
        dy = max(y0 + r - y, 0, y - (y1 - r))
        return dx * dx + dy * dy <= r * r
    (ax, ay), (bx, by), (cx, cy) = g
    d1 = (x - bx) * (ay - by) - (ax - bx) * (y - by)
    d2 = (x - cx) * (by - cy) - (bx - cx) * (y - cy)
    d3 = (x - ax) * (cy - ay) - (cx - ax) * (y - ay)
    neg = d1 < 0 or d2 < 0 or d3 < 0
    pos = d1 > 0 or d2 > 0 or d3 > 0
    return not (neg and pos)


def render(size, ss=4):
    """Returns rows of (r, g, b, a) tuples, top to bottom, antialiased by ss x ss supersampling."""
    shapes = SMALL if size <= 24 else FULL
    unit = 256.0 / size
    rows = []
    for py in range(size):
        row = []
        for px in range(size):
            acc = [0.0, 0.0, 0.0, 0.0]
            for sy in range(ss):
                for sx in range(ss):
                    x = (px + (sx + 0.5) / ss) * unit
                    y = (py + (sy + 0.5) / ss) * unit
                    color = None
                    for kind, c, g in shapes:
                        if inside(kind, g, x, y):
                            color = c
                    if color:
                        acc[0] += color[0]; acc[1] += color[1]; acc[2] += color[2]; acc[3] += 1
            n = ss * ss
            a = acc[3] / n
            if acc[3]:
                row.append((round(acc[0] / acc[3]), round(acc[1] / acc[3]), round(acc[2] / acc[3]), round(a * 255)))
            else:
                row.append((0, 0, 0, 0))
        rows.append(row)
    return rows


def png_bytes(rows):
    size = len(rows)
    raw = b"".join(b"\x00" + bytes(v for p in row for v in p) for row in rows)

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)) +
            chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def dib_bytes(rows):
    size = len(rows)
    header = struct.pack("<IiiHHIIiiII", 40, size, size * 2, 1, 32, 0, 0, 0, 0, 0, 0)
    xor = b"".join(bytes((b, g, r, a)) for row in reversed(rows) for (r, g, b, a) in row)
    stride = ((size + 31) // 32) * 4
    mask = bytearray()
    for row in reversed(rows):
        bits = bytearray(stride)
        for x, p in enumerate(row):
            if p[3] == 0:
                bits[x // 8] |= 0x80 >> (x % 8)
        mask += bits
    return header + xor + bytes(mask)


def ico_bytes(images):
    out = struct.pack("<HHH", 0, 1, len(images))
    offset = 6 + 16 * len(images)
    entries, blobs = b"", b""
    for size, data in images:
        dim = 0 if size >= 256 else size
        entries += struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32, len(data), offset)
        blobs += data
        offset += len(data)
    return out + entries + blobs


def svg_text():
    def hexc(c):
        return "#%02X%02X%02X" % c

    parts = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="256" height="256">',
             "  <!-- ARIB Player icon (generated by make-icon.py; sizes <= 24 px use the variant defined there) -->"]
    for kind, c, g in FULL:
        if kind == "rrect":
            x0, y0, x1, y1, r = g
            parts.append(f'  <rect x="{x0}" y="{y0}" width="{x1 - x0}" height="{y1 - y0}" rx="{r}" fill="{hexc(c)}"/>')
        else:
            pts = " ".join(f"{x},{y}" for x, y in g)
            parts.append(f'  <polygon points="{pts}" fill="{hexc(c)}"/>')
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview-dir")
    args = ap.parse_args()
    here = os.path.dirname(os.path.abspath(__file__))
    images = []
    for size in SIZES:
        rows = render(size)
        images.append((size, png_bytes(rows) if size >= 256 else dib_bytes(rows)))
        if args.preview_dir:
            os.makedirs(args.preview_dir, exist_ok=True)
            with open(os.path.join(args.preview_dir, f"preview-{size}.png"), "wb") as f:
                f.write(png_bytes(rows))
    with open(os.path.join(here, "aribplayer.ico"), "wb") as f:
        f.write(ico_bytes(images))
    with open(os.path.join(here, "aribplayer.svg"), "w", newline="\n") as f:
        f.write(svg_text())


if __name__ == "__main__":
    main()
